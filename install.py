#!/usr/bin/env python3
"""Install pstack's skills and agents into agent CLIs other than Claude Code.

Claude Code and the Claude Agent SDK load this repo as a plugin and need nothing here.

    python3 install.py                 # every detected harness
    python3 install.py codex opencode  # only these
    python3 install.py --copy gemini   # copy skills instead of symlinking them
    python3 install.py --project .     # install into a project instead of your home
    python3 install.py --uninstall     # remove what this script installed
"""

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

PSTACK = Path(__file__).resolve().parent
HOME = Path.home()
MARKER = "generated by pstack install.py"

PROJECT = {
    "codex": {"skills": ".agents/skills", "agents": ".codex/agents"},
    "opencode": {"skills": ".agents/skills", "agents": ".opencode/agents"},
    "amp": {"skills": ".agents/skills", "agents": None},
    "gemini": {"skills": ".agents/skills", "agents": ".gemini/agents"},
    "antigravity": {"skills": ".agents/skills", "agents": None},
}

HARNESSES = {
    "codex": {"detect": HOME / ".codex", "skills": HOME / ".agents/skills", "agents": HOME / ".codex/agents"},
    "opencode": {"detect": HOME / ".config/opencode", "skills": HOME / ".agents/skills", "agents": HOME / ".config/opencode/agents"},
    "amp": {"detect": HOME / ".config/amp", "skills": HOME / ".agents/skills", "agents": None},
    "gemini": {"detect": HOME / ".gemini", "skills": HOME / ".agents/skills", "agents": HOME / ".gemini/agents"},
    "antigravity": {"detect": HOME / ".gemini/antigravity-cli", "skills": HOME / ".gemini/antigravity-cli/skills", "agents": None},
}


def parse_agent(path):
    text = path.read_text()
    _, frontmatter, body = text.split("---", 2)
    fields = {}
    for line in frontmatter.strip().splitlines():
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    name = fields["name"]
    body = body.strip().replace("${CLAUDE_PLUGIN_ROOT}", str(PSTACK))
    body = re.sub(r"pstack:(poteto-agent|read-only|comment-sicko)", r"pstack-\1", body)
    preamble = (
        f"pstack is installed at `{PSTACK}`, with its skills in `{PSTACK}/skills`. "
        f"Map every Claude Code agent, tool, and parameter you read there with "
        f"`{PSTACK}/skills/poteto-mode/references/harnesses.md`."
    )
    return {
        "name": f"pstack-{name}",
        "description": fields["description"],
        "read_only": "Edit" in fields.get("disallowedTools", ""),
        "body": f"{preamble}\n\n{body}\n",
    }


def render(harness, agent):
    if harness == "codex":
        return (
            f"# {MARKER}\n"
            f"name = {json.dumps(agent['name'])}\n"
            f"description = {json.dumps(agent['description'])}\n"
            f"developer_instructions = {json.dumps(agent['body'])}\n"
        )
    lines = ["---"]
    if harness == "gemini":
        lines.append(f"name: {agent['name']}")
    lines.append(f"description: {json.dumps(agent['description'])}")
    if harness == "opencode":
        lines += ["mode: subagent", "permission:", "  external_directory:", f"    {json.dumps(str(PSTACK) + '/**')}: allow"]
        if agent["read_only"]:
            lines.append("  edit: deny")
    lines += ["---", f"<!-- {MARKER} -->", "", agent["body"]]
    return "\n".join(lines)


def install_skills(target, copy):
    target.mkdir(parents=True, exist_ok=True)
    for skill in sorted((PSTACK / "skills").iterdir()):
        if not (skill / "SKILL.md").exists():
            continue
        dest = target / skill.name
        if dest.is_symlink() and dest.resolve() == skill.resolve():
            if not copy:
                continue
            dest.unlink()
        elif dest.exists() or dest.is_symlink():
            if not (dest / f".{MARKER.replace(' ', '-')}").exists():
                print(f"  skip {dest}: already exists and is not pstack's")
                continue
            shutil.rmtree(dest) if dest.is_dir() and not dest.is_symlink() else dest.unlink()
        if copy:
            shutil.copytree(skill, dest, ignore=shutil.ignore_patterns("node_modules"))
            (dest / f".{MARKER.replace(' ', '-')}").touch()
        else:
            dest.symlink_to(skill)
    print(f"  skills -> {target}")


def uninstall_skills(target):
    if not target.is_dir():
        return
    for dest in target.iterdir():
        ours_link = dest.is_symlink() and PSTACK / "skills" in dest.resolve().parents
        ours_copy = dest.is_dir() and not dest.is_symlink() and (dest / f".{MARKER.replace(' ', '-')}").exists()
        if ours_link:
            dest.unlink()
        elif ours_copy:
            shutil.rmtree(dest)
    print(f"  removed pstack skills from {target}")


def install_agents(harness, target):
    target.mkdir(parents=True, exist_ok=True)
    suffix = ".toml" if harness == "codex" else ".md"
    for path in sorted((PSTACK / "agents").glob("*.md")):
        agent = parse_agent(path)
        dest = target / f"{agent['name']}{suffix}"
        if dest.exists() and MARKER not in dest.read_text():
            print(f"  skip {dest}: already exists and is not pstack's")
            continue
        dest.write_text(render(harness, agent))
    print(f"  agents -> {target}")


def uninstall_agents(target):
    if not target or not target.is_dir():
        return
    for dest in target.glob("pstack-*"):
        if MARKER in dest.read_text():
            dest.unlink()
    print(f"  removed pstack agents from {target}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("harnesses", nargs="*", choices=[*HARNESSES, "all"], metavar="HARNESS",
                        help=f"one or more of {', '.join(HARNESSES)}, or all (default: detected)")
    parser.add_argument("--copy", action="store_true", help="copy skills instead of symlinking them")
    parser.add_argument("--project", type=Path, metavar="DIR", help="install into this project instead of your home")
    parser.add_argument("--uninstall", action="store_true", help="remove what this script installed")
    args = parser.parse_args()

    if "all" in args.harnesses:
        chosen = list(HARNESSES)
    elif args.harnesses:
        chosen = args.harnesses
    else:
        chosen = [h for h, c in HARNESSES.items() if c["detect"].exists()]
    if not chosen:
        sys.exit("No supported harness detected. Name one: " + ", ".join(HARNESSES))

    done_skills = set()
    for harness in chosen:
        config = HARNESSES[harness]
        if args.project:
            root = args.project.resolve()
            config = {k: root / v if v else None for k, v in PROJECT[harness].items()}
        print(harness)
        if config["skills"] not in done_skills:
            (uninstall_skills if args.uninstall else lambda t: install_skills(t, args.copy))(config["skills"])
            done_skills.add(config["skills"])
        if config["agents"]:
            if args.uninstall:
                uninstall_agents(config["agents"])
            else:
                install_agents(harness, config["agents"])
        elif harness == "amp" and not args.uninstall:
            print(f"  Amp has no file-based agents. Its Task subagent takes the prompts in {PSTACK}/agents.")


if __name__ == "__main__":
    main()
